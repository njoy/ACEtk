void verifyChunk( const BandXPNData& chunk, std::vector< double >& xss, std::vector< std::vector< int > >& ans ) {


// XSS

  auto xss_chunk = chunk.XSS();
  for ( unsigned int i = 0; i < chunk.length(); ++i ) {

    CHECK_THAT( xss[i], WithinRel( xss_chunk[i] ) );
  }

// interface

  CHECK( 30 == chunk.NGRP() );
  CHECK( 30 == chunk.numberEnergyGroups() );

  CHECK( 29 == chunk.NDS() );
  CHECK( 29 == chunk.numberDownScatterGroups() );

  CHECK( 0 == chunk.NUS() );
  CHECK( 0 == chunk.numberUpScatterGroups() );

  CHECK( 465 == chunk.blockLength() );
  CHECK( 465 == chunk.length() );

  CHECK( 29 == chunk.groupDownScatterGroups( 1 ) );
  CHECK( 28 == chunk.groupDownScatterGroups( 2 ) );
  CHECK( 27 == chunk.groupDownScatterGroups( 3 ) );
  CHECK( 26 == chunk.groupDownScatterGroups( 4 ) );

  CHECK( 0 == chunk.groupUpScatterGroups( 1 ) );
  CHECK( 0 == chunk.groupUpScatterGroups( 2 ) );
  CHECK( 0 == chunk.groupUpScatterGroups( 3 ) );
  CHECK( 0 == chunk.groupUpScatterGroups( 4 ) );

  for ( int i = 0; i < 30; ++i) {

    for ( int j = 0; j < 30; ++j ) {

      CHECK( ans[i][j] == chunk.LPND( i+1, j+1) );
    }
  }

  auto mat = chunk.XPNMatrix();
  for (unsigned int row = 1; row <= 4; ++row ){
    for (unsigned int col = 1; col <= 4; ++col ) {
      CHECK_THAT( ans[row-1][col-1], WithinRel( mat[row-1][col-1] ) );
    }
  }
}

